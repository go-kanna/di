// with returns the files of base and more together.
func with(base, more map[string]string) map[string]string {
	files := maps.Clone(base)
	maps.Copy(files, more)
	return files
}

// writeModule writes files into a fresh module example.com/shop and returns
// its directory. The generated code calls nothing but the module's own
// packages, so the module requires nothing.
func writeModule(t *testing.T, files map[string]string) string {
	t.Helper()

	dir := t.TempDir()
	files["go.mod"] = "module example.com/shop\n\ngo 1.26.0\n"
	for name, content := range files {
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// execute runs kanna-di in dir and returns its exit code, stdout, and stderr.
func execute(t *testing.T, dir string, args ...string) (int, string, string) {
	t.Helper()

	var stdout, stderr bytes.Buffer
	code := gen.Command().Exec(cli.Env{Out: &stdout, Err: &stderr, Dir: dir}, args)
	return code, stdout.String(), stderr.String()
}

func readFile(t *testing.T, path string) string {
	t.Helper()

	b, err := os.ReadFile(path) //nolint:gosec // a file of the test's own module
	if err != nil {
		t.Fatalf("read %s: %v", path, err)
	}
	return string(b)
}

// build builds every package of the module in dir.
func build(t *testing.T, dir string) {
	t.Helper()
	gocmd(t, dir, "build", "./...")
}

// gotest runs the tests of pkg in the module in dir.
func gotest(t *testing.T, dir, pkg string) {
	t.Helper()
	gocmd(t, dir, "test", pkg)
}

func gocmd(t *testing.T, dir string, args ...string) {
	t.Helper()

	cmd := exec.CommandContext(t.Context(), "go", args...) //nolint:gosec // the go command, with what the test asks of it
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("go %s: %v\n%s", strings.Join(args, " "), err, out)
	}
}
