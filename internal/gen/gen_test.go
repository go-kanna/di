func TestCommand_ToleratesCallsOfAConstructorAboutToChange(t *testing.T) {
	t.Parallel()

	// What the last run wrote, when newUsers took nothing and returned the
	// users alone.
	const stale = "// Code generated by kanna-di. DO NOT EDIT.\n\npackage app\n\n" +
		"func newServer() *server {\n\tusers := newUsers()\n\n\treturn &server{\n\t\tusers: users,\n\t}\n}\n"

	tests := []struct {
		name, src string
	}{
		{
			// The caller passes the Config the constructor is about to take.
			name: "a parameter added",
			src: `package app

type (
	Config struct{}
	Users  struct{}
)

func newUsers(cfg Config) *Users { return &Users{} }

//kanna:container
type server struct {
	_ Config ` + "`di:\"arg=cfg\"`" + `

	users *Users
}

func run() { _ = newServer(Config{}) }
`,
		},
		{
			// The caller takes the cleanup the constructor is about to return.
			name: "a cleanup added",
			src: `package app

type Users struct{}

func newUsers() (*Users, func()) { return &Users{}, func() {} }

//kanna:container
type server struct {
	users *Users
}

func run() {
	_, cleanup := newServer()
	cleanup()
}
`,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, map[string]string{"app/server.go": tt.src, "app/di_gen.go": stale})
			if code, _, stderr := execute(t, filepath.Join(dir, "app")); code != cli.ExitOK || stderr != "" {
				t.Fatalf("exit %d, stderr %q", code, stderr)
			}
			build(t, dir)
		})
	}
}

