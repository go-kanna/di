// containers loads files as one package and finds its containers, as
// gen.Containers spells them.
func containers(t *testing.T, files map[string]string) ([]gen.Container, []string) {
	t.Helper()

	pkg := pkgtest.Load(t, files)
	return gen.Containers(pkg.Fset, []*packages.Package{pkg})
}

func TestContainers(t *testing.T) {
	t.Parallel()

	got, diags := containers(t, map[string]string{
		"server.go": `package test

import "fmt"

type (
	Env    string
	Config struct{ DSN string }
	Repo   interface{ Find() }
	Users  struct{}
	Deps   struct{ Repo Repo }
)

//kanna:container
type server struct {
	_ Repo ` + "`di:\"with=postgres.NewRepo\"`" + `

	users *Users
	env   Env    ` + "`di:\"arg\"`" + `
	cfg   Config ` + "`di:\"arg=config\"`" + `
	ready bool   ` + "`di:\"-\"`" + `
}

//kanna:container must
type Server struct {
	Deps ` + "`di:\"arg\"`" + `

	Users *Users
}

//kanna:container name=build must returns=Worker
type Worker struct{ Users *Users }

//kanna:container returns=fmt.Stringer
type named struct{ users *Users }

func (*named) String() string { return fmt.Sprint("named") }

// Plain has no directive and no di tags, so it is nobody's business.
type Plain struct{ Users *Users }
`,
		"server_test.go": `package test

//kanna:container
type testServer struct {
	_ Repo ` + "`di:\"arg\"`" + `

	*server
}
`,
		// What an earlier run left behind, which the next run replaces.
		"di_gen.go": `// Code generated by kanna-di. DO NOT EDIT.

package test

func newServer() *server { return nil }
`,
	})

	want := []gen.Container{
		{
			Name: "server", Ctor: "newServer", Returns: "*server",
			Fields: []string{
				"_: with postgres NewRepo",
				"users: type",
				"env: arg=env",
				"cfg: arg=config",
				"ready: -",
			},
		},
		{
			Name: "Server", Ctor: "NewServer", Must: "MustNewServer", Returns: "*Server",
			Fields: []string{"(embedded) Deps: arg=deps", "Users: type"},
		},
		{
			Name: "Worker", Ctor: "build", Must: "mustBuild", Returns: "Worker",
			Fields: []string{"Users: type"},
		},
		{
			Name: "named", Ctor: "newNamed", Returns: "fmt.Stringer",
			Fields: []string{"users: type"},
		},
		{
			Name: "testServer", Ctor: "newTestServer", Returns: "*testServer", Test: true,
			Fields: []string{"_: arg=repo", "(embedded) server: type"},
		},
	}
	if !reflect.DeepEqual(got, want) {
		t.Errorf("containers =\n%+v\nwant\n%+v", got, want)
	}
	if len(diags) > 0 {
		t.Errorf("diagnostics = %q, want none", diags)
	}
}

func TestContainers_Names(t *testing.T) {
	t.Parallel()

	tests := []struct {
		typeName, ctor, must string
	}{
		{typeName: "DB", ctor: "NewDB", must: "MustNewDB"},
		{typeName: "db", ctor: "newDb", must: "mustNewDb"},
		{typeName: "httpServer", ctor: "newHttpServer", must: "mustNewHttpServer"},
	}
	for _, tt := range tests {
		t.Run(tt.typeName, func(t *testing.T) {
			t.Parallel()

			got, diags := containers(t, map[string]string{
				"x.go": "package test\n\n//kanna:container must\ntype " + tt.typeName + " struct{}\n",
			})
			if len(got) != 1 || got[0].Ctor != tt.ctor || got[0].Must != tt.must {
				t.Errorf("containers = %+v, want %s and %s; diagnostics %q", got, tt.ctor, tt.must, diags)
			}
		})
	}
}

func TestContainers_ParamNames(t *testing.T) {
	t.Parallel()

	got, diags := containers(t, map[string]string{
		"x.go": `package test

type (
	URLPath    string
	HTTPClient struct{}
	ID         int
	Alias      = HTTPClient
)

//kanna:container
type c struct {
	_ URLPath     ` + "`di:\"arg\"`" + `
	_ *HTTPClient ` + "`di:\"arg\"`" + `
	_ ID          ` + "`di:\"arg\"`" + `
}

//kanna:container
type d struct {
	_ Alias ` + "`di:\"arg\"`" + `
}
`,
	})

	want := [][]string{
		{"_: arg=urlPath", "_: arg=httpClient", "_: arg=id"},
		{"_: arg=alias"},
	}
	if len(got) != len(want) || len(diags) > 0 {
		t.Fatalf("containers = %+v, diagnostics %q", got, diags)
	}
	for i := range want {
		if !reflect.DeepEqual(got[i].Fields, want[i]) {
			t.Errorf("%s fields = %q, want %q", got[i].Name, got[i].Fields, want[i])
		}
	}
}

func TestContainers_Diagnostics(t *testing.T) {
	t.Parallel()

	// Each source declares its container on line 5, after the types it uses
	// on line 3, so that the position a diagnostic carries can be told.
	tests := []struct {
		name string
		src  string
		want string
	}{
		{
			name: "generic",
			src:  "\n//kanna:container\ntype c[T any] struct{ v T }\n",
			want: "x.go:5:6: error: generic struct c cannot be a container",
		},
		{
			name: "unknown option",
			src:  "\n//kanna:container nme=b\ntype c struct{}\n",
			want: "x.go:4:1: error: unknown option \"nme=b\" of //kanna:container\n  did you mean \"name\"?",
		},
		{name: "name twice", src: "\n//kanna:container name=a name=b\ntype c struct{}\n", want: "name is given twice"},
		{name: "name empty", src: "\n//kanna:container name=\ntype c struct{}\n", want: "name= needs the constructor's name"},
		{
			name: "name not an identifier",
			src:  "\n//kanna:container name=1x\ntype c struct{}\n",
			want: "name=1x: 1x is not a Go identifier",
		},
		{name: "name blank", src: "\n//kanna:container name=_\ntype c struct{}\n", want: "_ is not a Go identifier"},
		{name: "must with a value", src: "\n//kanna:container must=true\ntype c struct{}\n", want: "must takes no value"},
		{name: "must twice", src: "\n//kanna:container must must\ntype c struct{}\n", want: "must is given twice"},
		{name: "returns empty", src: "\n//kanna:container returns=\ntype c struct{}\n", want: "returns= needs the type"},
		{
			name: "returns undefined",
			src:  "\n//kanna:container returns=service.Greeter\ntype c struct{}\n",
			want: "x.go:4:1: error: returns=service.Greeter: undefined: service",
		},
		{
			name: "returns that does not parse",
			src:  "\n//kanna:container returns=[]\ntype c struct{}\n",
			want: "x.go:4:1: error: returns=[]: expected type",
		},
		{
			name: "returns not a type",
			src:  "\n//kanna:container returns=len\ntype c struct{}\n",
			want: "returns=len: len is not a type",
		},
		{
			name: "returns another type",
			src:  "\n//kanna:container returns=Env\ntype c struct{}\n",
			want: "returns=Env: the constructor can return c, *c, or an interface *c implements, not Env",
		},
		{
			name: "returns an interface not implemented",
			src:  "\n//kanna:container returns=Reader\ntype c struct{}\n",
			want: "returns=Reader: *c does not implement Reader (missing method Read)",
		},
		{
			name: "blank without a tag",
			src:  "\n//kanna:container\ntype c struct {\n\t_ Env\n}\n",
			want: "x.go:6:2: error: a blank field must say what it declares",
		},
		{
			name: "blank skipped",
			src:  "\n//kanna:container\ntype c struct {\n\t_ Env `di:\"-\"`\n}\n",
			want: `di:"-" on a blank field says nothing; remove the field (field _)`,
		},
		{
			name: "malformed tag",
			src:  "\n//kanna:container\ntype c struct {\n\tenv Env `di:\"args\"`\n}\n",
			want: `x.go:6:2: error: unknown di tag "args"; write one of di:"-", di:"arg", di:"arg=<name>", ` +
				`or di:"with=<provider>" (field env)`,
		},
		{
			name: "argument of a type without a name",
			src:  "\n//kanna:container\ntype c struct {\n\t_ []string `di:\"arg\"`\n}\n",
			want: `[]string has no name to call the parameter by; write di:"arg=<name>" (field _)`,
		},
		{
			name: "argument hiding a predeclared name",
			src:  "\n//kanna:container\ntype c struct {\n\t_ Env `di:\"arg=nil\"`\n}\n",
			want: `di:"arg=nil": a parameter named nil would hide Go's own nil (field _)`,
		},
		{
			name: "argument taken twice",
			src:  "\n//kanna:container\ntype c struct {\n\t_ Env `di:\"arg\"`\n\tenv Env `di:\"arg=e\"`\n}\n",
			want: "x.go:7:2: error: Env is taken twice (line 6) (field env)",
		},
		{
			name: "two parameters of one name",
			src:  "\n//kanna:container\ntype c struct {\n\t_ Config `di:\"arg\"`\n\t_ *Config `di:\"arg\"`\n}\n",
			want: `two parameters are named config (line 6); name one with di:"arg=<name>" (field _)`,
		},
		{
			name: "chosen twice",
			src:  "\n//kanna:container\ntype c struct {\n\t_ Reader `di:\"with=a\"`\n\tr Reader `di:\"with=b\"`\n}\n",
			want: "Reader is chosen twice (line 6) (field r)",
		},
		{
			name: "taken and chosen",
			src:  "\n//kanna:container\ntype c struct {\n\t_ Reader `di:\"arg\"`\n\t_ Reader `di:\"with=b\"`\n}\n",
			want: "Reader is both taken as an argument and chosen with with= (line 6) (field _)",
		},
		{
			name: "tags without the directive",
			src:  "\ntype c struct {\n\t_ Env `di:\"arg\"`\n}\n",
			want: "x.go:4:6: warning: c has di tags but no //kanna:container, so nothing is generated for it",
		},
		{
			name: "unreadable tag without the directive",
			src:  "\ntype c struct {\n\tenv Env `di:\"arg`\n}\n",
			want: "warning: c has di tags but no //kanna:container",
		},
		{
			name: "constructor declared by hand",
			src:  "\n//kanna:container\ntype c struct{}\n\nfunc newC() *c { return nil }\n",
			want: "x.go:5:6: error: newC, the constructor of c, is already declared\n" +
				"  at x.go:7:6; rename one, or give the constructor a name with name=",
		},
		{
			name: "must variant declared by hand",
			src:  "\n//kanna:container must\ntype c struct{}\n\nvar mustNewC = 1\n",
			want: "mustNewC, the constructor of c, is already declared",
		},
		{
			name: "one constructor for two containers",
			src:  "\n//kanna:container name=build\ntype c struct{}\n\n//kanna:container name=build\ntype d struct{}\n",
			want: "x.go:8:6: error: build would be the constructor of both d and c (line 5)",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			src := "package test\n\ntype (Env string; Config struct{}; Reader interface{ Read() })" + tt.src
			_, diags := containers(t, map[string]string{"x.go": src})
			if !strings.Contains(strings.Join(diags, "\n"), tt.want) {
				t.Errorf("diagnostics = %q, want one to say %q", diags, tt.want)
			}
		})
	}
}

func TestContainers_LeavesOutTheContainersInError(t *testing.T) {
	t.Parallel()

	got, diags := containers(t, map[string]string{
		"x.go": "package test\n\n//kanna:container name=1x\ntype c struct{}\n\n//kanna:container\ntype d struct{}\n",
	})
	if len(got) != 1 || got[0].Name != "d" || len(diags) != 1 {
		t.Errorf("containers = %+v, diagnostics %q; want d alone and one diagnostic", got, diags)
	}
}
