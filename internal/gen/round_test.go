package gen_test

import (
	"slices"
	"strings"
	"testing"
)

const roundTypes = `package test

type (
	DB    struct{}
	Users struct{}
)

func newUsers() *Users { return nil }
func openDB() (*DB, error) { return nil, nil }
`

func TestPlans_AConstructorOfTheRun(t *testing.T) {
	t.Parallel()

	got, diags := plans(t, map[string]string{
		"x.go": roundTypes + `
// env is declared first, so it waits for the constructor of App.
//
//kanna:container
type env struct {
	app *App
}

//kanna:container must
type App struct {
	Users *Users
	DB    *DB
}
`,
		// What an earlier run generated, before App took a DB, is passed over,
		// must variant and all.
		"di_gen.go": `// Code generated by kanna-di. DO NOT EDIT.

package test

func NewApp() *App { return &App{} }

func MustNewApp() *App { return NewApp() }
`,
	})

	want := []string{"newEnv() (*env, error)", "app := NewApp() error", "env{app: app}"}
	if !slices.Equal(got["env"], want) || len(diags) > 0 {
		t.Errorf("env =\n\t%s\nwant\n\t%s\ndiagnostics %q",
			strings.Join(got["env"], "\n\t"), strings.Join(want, "\n\t"), diags)
	}
}

func TestPlans_LeaveOutARenamedConstructor(t *testing.T) {
	t.Parallel()

	// NewApp, which an earlier run generated before name= renamed the
	// constructor, goes with its file, so it is no provider of *App.
	got, diags := plans(t, map[string]string{
		"x.go": roundTypes + `
//kanna:container
type env struct {
	app *App
}

//kanna:container name=buildApp
type App struct {
	Users *Users
}
`,
		"di_gen.go": "// Code generated by kanna-di. DO NOT EDIT.\n\npackage test\n\nfunc NewApp() *App { return &App{} }\n",
	})

	want := []string{"newEnv() *env", "app := buildApp()", "env{app: app}"}
	if !slices.Equal(got["env"], want) || len(diags) > 0 {
		t.Errorf("env =\n\t%s\nwant\n\t%s\ndiagnostics %q",
			strings.Join(got["env"], "\n\t"), strings.Join(want, "\n\t"), diags)
	}
}

func TestPlans_AConstructorOfTheRunNamesItsParameters(t *testing.T) {
	t.Parallel()

	got, diags := plans(t, map[string]string{"x.go": `package test

type (
	Env    string
	Users  struct{}
	Report struct{}
)

func newUsers(env Env) *Users   { return nil }
func newReport(env Env) *Report { return nil }
func newEnvironment() Env       { return "" }

//kanna:container
type App struct {
	_ Env ` + "`di:\"arg=environment\"`" + `

	Users *Users
}

//kanna:container
type env struct {
	app    *App
	report *Report
}
`})

	// The Env the constructor of App takes is named as App names it.
	want := []string{
		"newEnv() *env",
		"environment := newEnvironment()",
		"app := NewApp(environment)",
		"report := newReport(environment)",
		"env{app: app, report: report}",
	}
	if !slices.Equal(got["env"], want) || len(diags) > 0 {
		t.Errorf("env =\n\t%s\nwant\n\t%s\ndiagnostics %q",
			strings.Join(got["env"], "\n\t"), strings.Join(want, "\n\t"), diags)
	}
}

func TestPlans_RoundDiagnostics(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name, src, want string
	}{
		{
			// Whichever is planned first, a function and a constructor of the
			// run returning one type are both candidates.
			name: "a constructor of the run and a function",
			src: `
func makeApp() *App { return nil }

//kanna:container
type env struct {
	app *App
}

//kanna:container name=buildApp
type App struct {
	Users *Users
}
`,
			want: "error: 2 functions in package test return *App\n  makeApp (x.go:11:6)\n  buildApp (x.go:19:6)\n",
		},
		{
			name: "a constructor of the run that cannot be generated",
			src: `
type Report struct{}

func newReport(a *App) *Report { return nil }

//kanna:container
type env struct {
	report *Report
}

//kanna:container
type App struct {
	Cache *Cache
}

type Cache struct{}
`,
			want: "x.go:17:2: error: *App is to come from NewApp, " +
				"which cannot be generated until the errors of App are fixed\n  via env.report → newReport\n",
		},
		{
			name: "constructors of the run needing each other",
			src: `
type Store struct{}

func newStore(a *App) *Store { return nil }

//kanna:container
type env struct {
	app   *App
}

//kanna:container
type App struct {
	E *env
}
`,
			want: "*App is to come from NewApp, which cannot be generated as App needs what newEnv builds in turn",
		},
		{
			name: "a constructor waiting for another in turn",
			src: `
//kanna:container
type a struct {
	b *B
}

//kanna:container
type B struct {
	c *C
}

//kanna:container
type C struct {
	Cache *Cache
}

type Cache struct{}
`,
			want: "*B is to come from NewB, which cannot be generated as it waits for another constructor in turn",
		},
		{
			name: "a constructor only tests compile",
			src: `
//kanna:container
type env struct {
	suite *suite
}
`,
			want: "  newSuite returns *suite but is declared in a _test.go file, which only tests compile\n",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			files := map[string]string{"x.go": roundTypes + tt.src}
			if strings.Contains(tt.src, "*suite") {
				files["x_test.go"] = "package test\n\n//kanna:container\ntype suite struct{ users *Users }\n"
			}
			_, diags := plans(t, files)
			if !strings.Contains(strings.Join(diags, "\n")+"\n", tt.want) {
				t.Errorf("diagnostics =\n%s\nwant one to say\n%s", strings.Join(diags, "\n"), tt.want)
			}
		})
	}
}
