func TestCommand_ReportsAMistakeBehindACallToItsConstructor(t *testing.T) {
	t.Parallel()

	// Before the run, go/types checks no further than undefined: newServer.
	tests := []struct {
		name  string
		files map[string]string
		want  string
	}{
		{
			name:  "a method that does not exist",
			files: map[string]string{"app/use.go": "package app\n\nfunc use() { newServer().bogus() }\n"},
			want:  "./use.go:3:26: error: newServer().bogus undefined (type *server has no field or method bogus)\n",
		},
		{
			name:  "assigned, then used",
			files: map[string]string{"app/use.go": "package app\n\nfunc use() {\n\ts := newServer()\n\ts.bogus()\n}\n"},
			want:  "./use.go:5:4: error: s.bogus undefined (type *server has no field or method bogus)\n",
		},
		{
			name: "passed where it does not fit",
			files: map[string]string{
				"app/use.go": "package app\n\nfunc take(int) {}\n\nfunc use() { take(newServer()) }\n",
			},
			want: "./use.go:5:19: error: cannot use newServer() (value of type *server) as int value in argument to take\n",
		},
		{
			name:  "in a test",
			files: map[string]string{"app/use_test.go": "package app\n\nfunc use() { newServer().bogus() }\n"},
			want:  "./use_test.go:3:26: error: newServer().bogus undefined (type *server has no field or method bogus)\n",
		},
		{
			name: "in an external test",
			files: map[string]string{
				"app/server.go": exportedUsers,
				"app/ext_test.go": "package app_test\n\nimport \"example.com/shop/app\"\n\n" +
					"func use() { app.NewServer().bogus() }\n",
			},
			want: "./ext_test.go:5:30: error: app.NewServer().bogus undefined " +
				"(type *app.Server has no field or method bogus)\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, with(map[string]string{"app/server.go": users}, tt.files))
			app := filepath.Join(dir, "app")
			if code, _, stderr := execute(t, app); code != cli.ExitFailure || stderr != tt.want {
				t.Errorf("exit %d, stderr:\n%s\nwant %d and\n%s", code, stderr, cli.ExitFailure, tt.want)
			}
			if _, err := os.Stat(filepath.Join(app, "di_gen.go")); err == nil {
				t.Error("di_gen.go was written")
			}
		})
	}
}

func TestCommand_ReportsACallTheConstructorDoesNotMatch(t *testing.T) {
	t.Parallel()

	// What the last run wrote, when newUsers took nothing and returned the
	// users alone, and what the callers still call.
	const stale = "// Code generated by kanna-di. DO NOT EDIT.\n\npackage app\n\n" +
		"func newServer() *server {\n\tusers := newUsers()\n\n\treturn &server{\n\t\tusers: users,\n\t}\n}\n"

	tests := []struct {
		name, src, want string
	}{
		{
			name: "a parameter added",
			src: `package app

type (
	Config struct{}
	Users  struct{}
)

func newUsers(cfg Config) *Users { return &Users{} }

//kanna:container
type server struct {
	_ Config ` + "`di:\"arg=cfg\"`" + `

	users *Users
}

func run() { _ = newServer() }
`,
			want: "./server.go:17:28: error: not enough arguments in call to newServer\n\thave ()\n\twant (Config)\n",
		},
		{
			name: "an error added",
			src: `package app

type Users struct{}

func newUsers() (*Users, error) { return &Users{}, nil }

//kanna:container
type server struct {
	users *Users
}

func run() {
	s := newServer()
	_ = s
}
`,
			want: "./server.go:13:7: error: assignment mismatch: 1 variable but newServer returns 2 values\n",
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, map[string]string{"app/server.go": tt.src, "app/di_gen.go": stale})
			app := filepath.Join(dir, "app")
			for _, args := range [][]string{nil, {"-check"}} {
				if code, _, stderr := execute(t, app, args...); code != cli.ExitFailure || stderr != tt.want {
					t.Errorf("%q: exit %d, stderr:\n%s\nwant %d and\n%s", args, code, stderr, cli.ExitFailure, tt.want)
				}
			}
			if got := readFile(t, filepath.Join(app, "di_gen.go")); got != stale {
				t.Errorf("di_gen.go was rewritten:\n%s", got)
			}
		})
	}
}

func TestCommand_KeepsWhatCodeStillCalls(t *testing.T) {
	t.Parallel()

	const src = `package app

type Users struct{}

func newUsers() (*Users, error) { return &Users{}, nil }

//kanna:container must
type server struct {
	users *Users
}
`
	tests := []struct {
		name, edit, with string
	}{
		{name: "the directive goes", edit: "//kanna:container must\n"},
		{name: "the must variant goes", edit: "//kanna:container must", with: "//kanna:container"},
		{name: "the constructor renamed", edit: "//kanna:container must", with: "//kanna:container must name=newApp"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			dir := writeModule(t, map[string]string{
				"app/server.go": src,
				"app/main.go":   "package app\n\nfunc run() { _ = mustNewServer() }\n",
			})
			app := filepath.Join(dir, "app")
			if code, _, stderr := execute(t, app); code != cli.ExitOK {
				t.Fatalf("exit %d, stderr %q", code, stderr)
			}
			generated := readFile(t, filepath.Join(app, "di_gen.go"))

			path := filepath.Join(app, "server.go")
			if err := os.WriteFile(path, []byte(strings.Replace(src, tt.edit, tt.with, 1)), 0o600); err != nil {
				t.Fatal(err)
			}
			want := "./main.go:3:18: error: undefined: mustNewServer\n"
			if code, _, stderr := execute(t, app); code != cli.ExitFailure || stderr != want {
				t.Errorf("exit %d, stderr:\n%s\nwant %d and\n%s", code, stderr, cli.ExitFailure, want)
			}
			if got := readFile(t, filepath.Join(app, "di_gen.go")); got != generated {
				t.Errorf("di_gen.go was rewritten:\n%s", got)
			}
		})
	}
}

