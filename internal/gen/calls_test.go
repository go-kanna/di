func TestCommand_RegeneratesAnOutputSetAsideWhole(t *testing.T) {
	t.Parallel()

	// What the last run wrote no longer compiles even with its bodies
	// stubbed, so it is set aside whole, and newServer with it.
	const stale = "// Code generated by kanna-di. DO NOT EDIT.\n\npackage app\n\n" +
		"func newServer(cfg Settings) *server { return nil }\n"
	const src = `package app

type (
	Config struct{}
	Users  struct{}
)

func newUsers(cfg Config) *Users { return &Users{} }

//kanna:container
type server struct {
	_ Config ` + "`di:\"arg=cfg\"`" + `

	users *Users
}
`

	t.Run("called as it is about to be", func(t *testing.T) {
		t.Parallel()

		dir := writeModule(t, map[string]string{
			"app/server.go": src,
			"app/main.go":   "package app\n\nfunc run() { _ = newServer(Config{}) }\n",
			"app/di_gen.go": stale,
		})
		if code, _, stderr := execute(t, filepath.Join(dir, "app")); code != cli.ExitOK || stderr != "" {
			t.Fatalf("exit %d, stderr %q", code, stderr)
		}
		build(t, dir)
	})

	t.Run("with a mistake behind the call", func(t *testing.T) {
		t.Parallel()

		dir := writeModule(t, map[string]string{
			"app/server.go": src,
			"app/main.go":   "package app\n\nfunc run() { newServer(Config{}).bogus() }\n",
			"app/di_gen.go": stale,
		})
		app := filepath.Join(dir, "app")
		want := "./main.go:3:34: error: newServer(Config{}).bogus undefined (type *server has no field or method bogus)\n" +
			"./di_gen.go: warning: set aside because it no longer compiles; it is regenerated once the errors above are fixed\n"
		if code, _, stderr := execute(t, app); code != cli.ExitFailure || stderr != want {
			t.Errorf("exit %d, stderr:\n%s\nwant %d and\n%s", code, stderr, cli.ExitFailure, want)
		}
		if got := readFile(t, filepath.Join(app, "di_gen.go")); got != stale {
			t.Errorf("di_gen.go was rewritten:\n%s", got)
		}
	})
}

